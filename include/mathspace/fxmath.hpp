// Position of the highest set bit of a non-zero word, by six fixed halving
// steps rather than a loop or a builtin.
constexpr unsigned msb64(std::uint64_t m) {
    unsigned n = 0;
    if (m >> 32) { m >>= 32; n += 32; }
    if (m >> 16) { m >>= 16; n += 16; }
    if (m >> 8) { m >>= 8; n += 8; }
    if (m >> 4) { m >>= 4; n += 4; }
    if (m >> 2) { m >>= 2; n += 2; }
    if (m >> 1) { n += 1; }
    return n;
}

// |v| as an unsigned word; INT64_MIN maps to 2^63 without signed overflow.
constexpr std::uint64_t umag(std::int64_t v) {
    return v < 0 ? (std::uint64_t{0} - static_cast<std::uint64_t>(v)) : static_cast<std::uint64_t>(v);
}

// Arithmetic shift by a signed amount: left for s > 0, right (floor) for
// s < 0. Callers keep |s| < 64.
constexpr std::int64_t shift_signed(std::int64_t v, int s) {
    return s >= 0 ? static_cast<std::int64_t>(static_cast<std::uint64_t>(v) << s) : (v >> (-s));
}

// Q3.60 to Q32.32. The CORDIC working value is off by up to about 2^-47
// in either direction, so this rounds to nearest rather than flooring: a
// floor would turn sin(0) into -2^-32 and cos(0) into 1 - 2^-32. exp and
// log never over-approximate and keep the floor.
constexpr std::int64_t to_grid(std::int64_t q60) {
    return (q60 + (std::int64_t{1} << 27)) >> 28;
}

struct SinCos {
    fx64 sin;
    fx64 cos;
};

// Both at once, since CORDIC produces both. The angle is reduced modulo
// 2 pi: k = floor(angle / TWO_PI_32) on the Q32.32 grid (the multiply
// below wraps for the largest inputs; -fwrapv makes that defined and the
// residue is still correct modulo 2^64), then the residue is refined in
// Q3.60 with 2 pi carried to 88 fractional bits (TWO_PI_32, TWO_PI_MID,
// TWO_PI_LO), so a full-range input loses about 2^-59 of angle rather than
// half an ulp per period. TWO_PI_32 is below 2 pi, so k can be one too
// large and one correction brings the residue back into [0, 2 pi). The
// residue is folded into [-pi/2, pi/2] and rotated.
constexpr SinCos sincos(fx64 angle) {
    const std::int64_t k = div_q32(angle.raw, TWO_PI_32) >> 32;  // |k| < 2^29
    std::int64_t r = ((angle.raw - k * TWO_PI_32) << 28) - k * TWO_PI_MID - ((k * TWO_PI_LO) >> 28);
    if (r < 0) {
        r += TWO_PI_60;  // [0, 2 pi)
    }
    if (r > PI_60) {
        r -= TWO_PI_60;  // (-pi, pi]
    }
    bool negate_cos = false;
    if (r > HALF_PI_60) {
        r = PI_60 - r;
        negate_cos = true;
    } else if (r < -HALF_PI_60) {
        r = -PI_60 - r;
        negate_cos = true;
    }
    std::int64_t x = CORDIC_K_60;
    std::int64_t y = 0;
    std::int64_t z = r;  // |r| <= pi/2 in Q3.60
    for (unsigned i = 0; i < CORDIC_ITER; ++i) {
        const std::int64_t xs = x >> i;
        const std::int64_t ys = y >> i;
        if (z >= 0) {
            x -= ys;
            y += xs;
            z -= ATAN_60[i];
        } else {
            x += ys;
            y -= xs;
            z += ATAN_60[i];
        }
    }
    if (negate_cos) {
        x = -x;
    }
    return SinCos{fx64::from_raw(to_grid(y)), fx64::from_raw(to_grid(x))};
}

constexpr fx64 sin(fx64 angle) { return sincos(angle).sin; }
constexpr fx64 cos(fx64 angle) { return sincos(angle).cos; }

// Angle of (x, y) in (-pi, pi]. atan2(0, 0) is 0. The pair is scaled by a
// common power of two so the larger magnitude has its top bit at 59 (the
// CORDIC gain of 1.647 then keeps every intermediate below 2^62), a
// negative x is flipped through the origin and the half turn added back.
constexpr fx64 atan2(fx64 y, fx64 x) {
    if (x.raw == 0 && y.raw == 0) {
        return fx64::from_raw(0);
    }
    const std::uint64_t m = umag(x.raw) > umag(y.raw) ? umag(x.raw) : umag(y.raw);
    const int s = 59 - static_cast<int>(msb64(m));
    std::int64_t vx = shift_signed(x.raw, s);
    std::int64_t vy = shift_signed(y.raw, s);
    const bool flipped = vx < 0;
    if (flipped) {
        vx = -vx;
        vy = -vy;
    }
    std::int64_t z = 0;
    for (unsigned i = 0; i < CORDIC_ITER; ++i) {
        const std::int64_t xs = vx >> i;
        const std::int64_t ys = vy >> i;
        if (vy >= 0) {
            vx += ys;
            vy -= xs;
            z += ATAN_60[i];
        } else {
            vx -= ys;
            vy += xs;
            z -= ATAN_60[i];
        }
    }
    if (flipped) {
        z = y.raw >= 0 ? z + PI_60 : z - PI_60;
    }
    return fx64::from_raw(to_grid(z));
}

// e^t for t = n ln2 + r given as a Q5.58 exponent: r in [0, ln2) is
// decomposed greedily over ln(1 + 2^-i), the matching factors multiply
// into y, and y (in [1, 2) Q5.58) is scaled by 2^n onto the Q32.32 grid.
// Saturates at INT64_MAX when the result would not fit (n >= 31, or n == 30
// with y reaching 2), and floors to 0 when it would.
constexpr std::int64_t exp_core(std::int64_t t58) {
    std::int64_t n = t58 / LN2_58;
    std::int64_t r = t58 - n * LN2_58;
    if (r < 0) {  // C++ division truncates toward zero; floor it
        r += LN2_58;
        n -= 1;
    }
    std::int64_t y = std::int64_t{1} << 58;
    for (unsigned i = 1; i <= BKM_ITER; ++i) {
        if (r >= LN1P_58[i]) {
            r -= LN1P_58[i];
            y += y >> i;
        }
    }
    const int s = static_cast<int>(n) - 26;  // Q5.58 * 2^n to Q32.32
    if (s > 4 || (s == 4 && y >= (std::int64_t{1} << 59))) {
        return INT64_MAX;
    }
    if (s < -63) {
        return 0;
    }
    return shift_signed(y, s);
}

// ln x as Q5.58 for x > 0 (the caller has checked): x = m 2^e with m in
// [1, 2) as Q5.58; ln m by dividing out the factors 1 + 2^-i, then e ln2
// added. |result| < 23 ln2 < 16, well inside Q5.58.
constexpr std::int64_t log_core(std::int64_t raw) {
    const int e = static_cast<int>(msb64(static_cast<std::uint64_t>(raw))) - 32;
    const std::int64_t m = shift_signed(raw, 26 - e);  // top bit at 58: [1, 2) Q5.58
    std::int64_t y = std::int64_t{1} << 58;
    std::int64_t r = 0;
    for (unsigned i = 1; i <= BKM_ITER; ++i) {
        const std::int64_t t = y + (y >> i);
        if (t <= m) {
            y = t;
            r += LN1P_58[i];
        }
    }
    return r + e * LN2_58;
}

// The exponent range exp_core accepts: above it the result saturates,
// below it the result floors to 0 (e^x * 2^32 < 1/2). Both are ordinary
// results, not contract violations.
inline constexpr std::int64_t EXP_MAX_32 = 31 * LN2_32;
inline constexpr std::int64_t EXP_MIN_32 = -33 * LN2_32;

// e^x. The Q32.32 input is exact in Q5.58 once inside the accepted range.
constexpr fx64 exp(fx64 x) {
    if (x.raw >= EXP_MAX_32) {
        return fx64::from_raw(INT64_MAX);
    }
    if (x.raw < EXP_MIN_32) {
        return fx64::from_raw(0);
    }
    return fx64::from_raw(exp_core(x.raw << 26));
}

// ln x for x > 0, floored to the grid. Non-positive x returns 0 (and
// asserts in Debug).
constexpr fx64 log(fx64 x) {
    DDSIM_ASSERT(x.raw > 0);
    if (x.raw <= 0) {
        return fx64::from_raw(0);
    }
    return fx64::from_raw(log_core(x.raw) >> 26);
}

// x^y for x > 0: exp(y ln x) with the product formed in Q5.58, so the
// result carries the same relative error as exp (about 2^-50), not one
// that grows with |y|. The range check runs on a Q32.32 copy of the
// product first, so the Q5.58 product is only formed when it fits.
// x <= 0 returns 0 (and asserts in Debug); y == 0 gives 1 for any x > 0.
constexpr fx64 pow(fx64 x, fx64 y) {
    DDSIM_ASSERT(x.raw > 0);
    if (x.raw <= 0) {
        return fx64::from_raw(0);
    }
    const std::int64_t l58 = log_core(x.raw);
    const std::int64_t t32 = mul_q32(y.raw, l58 >> 26);
    if (t32 >= EXP_MAX_32) {
        return fx64::from_raw(INT64_MAX);
    }
    if (t32 < EXP_MIN_32 - fx64::ONE) {  // a whole unit of slack for the coarse product
        return fx64::from_raw(0);
    }
    return fx64::from_raw(exp_core(mul_q32(y.raw, l58)));
}

