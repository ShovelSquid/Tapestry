// mathspace/fxmath.hpp — transcendental functions over fx64 with fixed work.
//
// sin, cos, atan2, exp, log, pow. Each one runs the same integer instruction
// sequence for every input: the loops have literal bounds, there is no
// convergence test, no early exit, and no recursion (fxmath_test.cpp scans
// this file for `while`, `do`, `goto` and non-literal `for` bounds). Debug,
// Release, UBSan and Wasm therefore agree bit for bit, and a rule that calls
// sin ten thousand times a tick costs the same ten thousand times.
//
// Method. sin/cos/atan2 are CORDIC (rotation and vectoring mode) in a Q3.60
// working format for CORDIC_ITER = 48 iterations, which puts the angle
// residual near 2^-48 and the result, rounded to the grid, within one
// Q32.32 ulp of the true value. exp and log are the shift-and-add ("BKM") scheme over the factors
// 1 + 2^-i, i = 1..BKM_ITER = 58, in Q5.58: exp multiplies the factors
// whose logs fit under the residual, log divides them out of the mantissa.
// pow is exp(y * log(x)) with the product on the Q32.32 grid, so its
// relative error grows linearly with |y| (about |y| * 2^-32).
//
// Every constant is floor(value * 2^k), generated by tools/gen_fxmath/gen.py
// (mpmath at 60 digits); nothing here is computed from a floating-point
// value at compile time or run time.
//
// Contract violations follow fx64.hpp: log of a non-positive value and pow
// of a non-positive base return 0 in every build and assert in Debug. exp
// saturates at the largest fx64 when the result would not fit, and
// returns 0 when it would floor to 0; both are ordinary results, not
// violations.
